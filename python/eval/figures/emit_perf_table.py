"""Generate the paper's performance tables from criterion's output.

The numbers in ``tab:perf`` used to be transcribed by hand from a benchmark log. Three separate
defects came out of that arrangement, and none of them was a mistake in the *measurement*:

- the write row was measured at ``n = 10^3`` while the sentence quoting it said ``n = 10^4``;
- the write row was measured at ``dim = 128`` while the caption said ``768``;
- a stale n = 10^4 column survived a machine change, so criterion's own "no change in
  performance detected" was comparing a fresh honest number against a contended old one, and
  agreed with it.

A table that is *generated* cannot drift from the run that produced it. This reads
``target/criterion`` directly, writes ``paper/tables/perf.tex``, and stamps the provenance --
dimension, spread, machine -- into the file so a reader of the source can see what produced it.

Usage::

    cd python && python -m eval.figures.emit_perf_table --baseline frozen-s1

The generated file is committed, so building the paper does not require running the benchmark.
Regenerate it whenever the benchmark is re-run, and never edit it by hand: it says so at the top
of the generated output.
"""

from __future__ import annotations

import argparse
import json
import platform
from pathlib import Path

from eval.lab import corpus as C

#: Display name, criterion id. Order is the order of the table rows.
SCHEMES = [
    ("Plaintext IVF", "plaintext_ivf"),
    ("Naive encrypt-then-search", "naive_ets"),
    ("Sophos-FP", "sophos_fp"),
    ("Diana-FP", "diana_fp"),
]

SIZES = (1000, 10000)


def median_us(root: Path, group: str, name: str, size: int | None, baseline: str) -> float | None:
    parts = [root, "target", "criterion", group, name]
    if size is not None:
        parts.append(str(size))
    path = Path(*[str(p) for p in parts]) / baseline / "estimates.json"
    if not path.exists():
        return None
    return json.loads(path.read_text(encoding="utf-8"))["median"]["point_estimate"] / 1000.0


def fmt(us: float | None) -> str:
    """Latency with a unit, at three significant figures.

    Mixing units inside a column is deliberate: a reader comparing $72\\,\\mu s$ against
    $35\\,ms$ should see the unit change rather than count zeros.
    """
    if us is None:
        return "n/a"
    if us >= 1000.0:
        return f"${us / 1000.0:.2f}\\,ms$"
    return f"${us:.1f}\\,\\mu s$"


def growth(a: float | None, b: float | None) -> str:
    if a is None or b is None or a == 0:
        return "n/a"
    return f"${b / a:.1f}\\times$"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--baseline", default="frozen-s1", help="criterion baseline directory name")
    ap.add_argument(
        "--baseline-s2",
        default="frozen-s2",
        help="criterion baseline holding the shipped-default (s=2) Mnemos measurements",
    )
    ap.add_argument("--dim", type=int, default=768)
    args = ap.parse_args()

    root = C.repo_root()
    out = root / "paper" / "tables" / "perf.tex"
    out.parent.mkdir(parents=True, exist_ok=True)

    lines: list[str] = []
    w = lines.append

    w("% GENERATED by python -m eval.figures.emit_perf_table -- DO NOT EDIT BY HAND.")
    w("% Every number below is read straight out of target/criterion. Editing this file makes")
    w("% the paper disagree with the benchmark that produced it, silently.")
    w(f"% dim = {args.dim}; machine = {platform.system()} {platform.machine()};")
    w(f"% baselines: {args.baseline} (s=1), {args.baseline_s2} (s=2, the shipped default)")
    w("\\begin{tabular}{lrrr}")
    w("\\toprule")
    w("Scheme & $n=1{,}000$ & $n=10{,}000$ & Growth \\\\")
    w("\\midrule")

    for label, key in SCHEMES:
        a = median_us(root, "search", key, SIZES[0], args.baseline)
        b = median_us(root, "search", key, SIZES[1], args.baseline)
        w(f"{label} & {fmt(a)} & {fmt(b)} & {growth(a, b)} \\\\")

    w("\\midrule")
    for label, key, base in [
        ("\\textbf{Mnemos} ($s=1$, $d=0$)", "mnemos_d0", args.baseline),
        ("\\textbf{Mnemos} ($s=1$, $d=4$)", "mnemos_d4", args.baseline),
        ("\\textbf{Mnemos} ($s=2$, $d=0$) \\emph{default}", "mnemos_d0", args.baseline_s2),
        ("\\textbf{Mnemos} ($s=2$, $d=4$)", "mnemos_d4", args.baseline_s2),
    ]:
        a = median_us(root, "search", key, SIZES[0], base)
        b = median_us(root, "search", key, SIZES[1], base)
        w(f"{label} & {fmt(a)} & {fmt(b)} & {growth(a, b)} \\\\")

    w("\\bottomrule")
    w("\\end{tabular}")

    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out.relative_to(root)}")

    # --- the write-side table, and the overhead multiple the abstract quotes ---
    wl: list[str] = []
    v = wl.append
    v("% GENERATED by python -m eval.figures.emit_perf_table -- DO NOT EDIT BY HAND.")
    v("\\begin{tabular}{lrrr}")
    v("\\toprule")
    v("Operation & $n=1{,}000$ & $n=10{,}000$ & vs plaintext \\\\")
    v("\\midrule")

    ratios: dict[int, float] = {}
    rows = [
        ("Mnemos \\texttt{put}, amortized over a flush", "put_amortised"),
        ("Plaintext IVF \\texttt{put}", "plaintext_put"),
    ]
    # `put_amortised` times one full batch of `epoch_writes` puts per iteration, the last of
    # which triggers the flush; the per-put figure is that time divided by the batch size.
    batch = 16
    vals = {
        key: {n: median_us(root, "write", key, n, args.baseline) for n in SIZES} for _, key in rows
    }
    for n in SIZES:
        if vals["put_amortised"][n] is not None:
            vals["put_amortised"][n] /= batch
    for n in SIZES:
        mn, pl = vals["put_amortised"][n], vals["plaintext_put"][n]
        if mn is not None and pl:
            ratios[n] = mn / pl

    for label, key in rows:
        a, b = vals[key][SIZES[0]], vals[key][SIZES[1]]
        if key == "put_amortised":
            tail = f"${ratios.get(SIZES[1], 0):.0f}\\times$" if SIZES[1] in ratios else "n/a"
        elif key == "plaintext_put":
            tail = "$1\\times$"
        else:
            tail = "n/a"
        v(f"{label} & {fmt(a)} & {fmt(b)} & {tail} \\\\")
    v("\\bottomrule")
    v("\\end{tabular}")

    out2 = root / "paper" / "tables" / "write.tex"
    out2.write_text("\n".join(wl) + "\n", encoding="utf-8")
    print(f"wrote {out2.relative_to(root)}")

    # Printed rather than embedded: these go into prose in three places, and a human has to put
    # them there. Printing them here is what keeps the prose and the table on the same run.
    print("\n  numbers the prose quotes:")
    for n in SIZES:
        s1 = median_us(root, "search", "mnemos_d0", n, args.baseline)
        s2 = median_us(root, "search", "mnemos_d0", n, args.baseline_s2)
        pl = median_us(root, "search", "plaintext_ivf", n, args.baseline)
        if s1 and pl:
            print(f"    n={n:>6}  search overhead s=1: {s1 / pl:5.1f}x", end="")
            if s2:
                print(f"   s=2 (default): {s2 / pl:5.1f}x", end="")
            print()
    for n, r in ratios.items():
        print(f"    n={n:>6}  write overhead: {r:5.1f}x")


if __name__ == "__main__":
    main()
